#!/bin/bash
rm -f cpu_stat.log
echo "================================================="
echo "正在启动 CPU 实验：用户态 vs 内核态"
echo "程序将运行 5 秒，请观察数据变化..."
echo "================================================="

# 1. 启动后台监控，每秒采集一次，总共 5 次
sar -u 1 5 > cpu_stat.log &
SAR_PID=$!

# 2. 运行你的压测程序（确保你已经编译了它）
# 假设程序在当前目录，运行 5 秒后杀死它
timeout 5 ./../build/cpu/cpu_high_sys & 
PROG_PID=$!

# 等待监控完成
wait $SAR_PID

echo -e "\n[CPU 性能实验报告]"
echo "-------------------------------------------------"
# 打印表头和数据，只看有数据的行，并按时间排序
grep -E "all|%user" cpu_stat.log | sort -k1

echo -e "\n[分析指南]"
echo "1. 看 %system：如果该值 > 50%，说明系统调用太频繁（比如频繁读写小文件）。"
echo "2. 看 %user：这是你程序真正干活的时间，值越高说明算法效率利用率越高。"
echo "3. 思考：为什么 %system 高会导致系统卡顿？因为内核态优先级极高，它会挤占键盘输入、鼠标移动等处理时间。"

